r = await tenta({ ...a, aal: 'aal2' }, `insert into public.clientes (nome) values ('Ação — São João & Filhos (Ltda.)')`); ok(!r.erro, 'nomes com acento, travessão, &, parênteses e ponto continuam aceitos (sem falso positivo)');

console.log('\n## Injeção de SQL (dados de teste, ambiente isolado)');
const payloads = ["' OR '1'='1", "'; DROP TABLE public.clientes; --", "x' UNION SELECT token FROM public.propostas --", '" OR ""="', "1; SELECT pg_sleep(5)"];
let alterou = false;
const antes = (await q(`select (select count(*) from public.clientes)::int c, (select count(*) from public.propostas)::int p, (select count(*) from public.profiles)::int u`)).rows[0];
for (const pl of payloads) {
  const t1 = await tenta(null, `select public.proposta_publica($1) as x`, [pl]);
  const t2 = await tenta(null, `select public.projeto_publico($1) as x`, [pl]);
  const t3 = await tenta(null, `select public.avaliacao_publica($1) as x`, [pl]);
  const t4 = await tenta(null, `select public.responder_proposta($1, true, $1, $1) as x`, [pl]);
  const t5 = await tenta(null, `select public.responder_avaliacao($1, 5, $1, $1, true) as x`, [pl]);
  if ([t1, t2, t3].some((t) => t.r && t.r.rows[0].x !== null)) alterou = true;
  if (t4.r && t4.r.rows[0].x === 'ok') alterou = true;
  if (t5.r && t5.r.rows[0].x === 'ok') alterou = true;
  await tenta({ ...a, aal: 'aal2' }, `insert into public.clientes (nome, observacoes) values ($1, $1)`, [pl + Math.random()]);
}
const depois = (await q(`select (select count(*) from public.clientes)::int c, (select count(*) from public.propostas)::int p, (select count(*) from public.profiles)::int u`)).rows[0];
ok(!alterou, 'funções públicas tratam payloads de injeção como texto: nenhuma devolve dado nem aceita resposta');
ok(depois.c === antes.c + payloads.length && depois.p === antes.p && depois.u === antes.u, 'as tabelas continuam intactas e os payloads foram gravados como texto comum');
const dyn = (await q(`select p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.prolang = (select oid from pg_language where lanname = 'plpgsql') and p.prosrc ~* '\\mexecute\\M'`)).rows.map((x) => x.proname);
ok(dyn.length === 1 && dyn[0] === 'interacao_preenche', 'o único SQL dinâmico do banco é interacao_preenche (usa %I sobre lista fechada por CHECK): ' + dyn.join(','));
r = await tenta({ ...a, aal: 'aal2' }, `insert into public.interacoes (entidade, entidade_id, tipo, texto) values ('clientes; drop table public.clientes', gen_random_uuid(), 'nota', 'x')`);
ok(r.erro && (await q(`select count(*)::int n from public.clientes`)).rows[0].n > 0, 'nome de tabela malicioso em interacoes é barrado pelo CHECK antes do SQL dinâmico');

console.log('\n## Funções, tabelas e buckets');
const execAnon = (await q(`select p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and has_function_privilege('anon', p.oid, 'execute') and p.prosecdef order by 1`)).rows.map((x) => x.proname);
const esperadas = ['avaliacao_publica', 'projeto_publico', 'proposta_publica', 'registrar_login_falho', 'responder_avaliacao', 'responder_proposta'];
ok(JSON.stringify(execAnon) === JSON.stringify(esperadas), 'visitante só executa as 6 funções públicas esperadas: ' + execAnon.join(', '));
const trig = (await q(`select p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and has_function_privilege('anon', p.oid, 'execute') and p.prorettype = 'trigger'::regtype`)).rows;
ok(trig.length === 0, 'nenhuma função de trigger é executável por visitante (touch() corrigida)');
ok((await q(`select count(*)::int n from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'r' and not c.relrowsecurity`)).rows[0].n === 0, 'toda tabela do schema public tem RLS ligada');
const aberta = (await q(`select tablename || '.' || policyname as x from pg_policies where schemaname = 'public' and (roles::text like '%anon%' or roles::text like '%public%') order by 1`)).rows.map((x) => x.x);
ok(JSON.stringify(aberta) === JSON.stringify(['contatos_site.contatos_insert_publico', 'portfolio_cases.pf_publico']), 'só 2 políticas valem para visitante (enviar lead, ler portfólio publicado): ' + aberta.join(', '));
const mime = (await q(`select allowed_mime_types from storage.buckets where id = 'projetos'`)).rows[0].allowed_mime_types;
ok(Array.isArray(mime) && !mime.includes('text/html') && !mime.includes('image/svg+xml') && mime.includes('application/pdf'), 'anexos de projeto: HTML e SVG não são aceitos');
r = await tenta(null, `select * from public.eventos_seguranca`); ok((r.r?.rows.length ?? 0) === 0, 'visitante não lê o log de segurança');
r = await tenta(null, `select * from public.config_seguranca`); ok((r.r?.rows.length ?? 0) === 0, 'visitante não lê a configuração de segurança');
r = await tenta(m, `select * from public.seguranca_sal`); ok((r.r?.rows.length ?? 0) === 0, 'ninguém lê o sal dos hashes pelo navegador');
void cli;
fim('sql-seguranca');
