// Testes de segurança do banco (migrations 001–014): sessão, 2FA, eventos, limites, validações, injeção e permissões.
import { criarBanco, papeis, relatorio } from './banco.mjs';

const db = await criarBanco();
const { as, tenta, q } = papeis(db);
const { ok, fim } = relatorio();

const A = '00000000-0000-0000-0000-00000000000a', M = '00000000-0000-0000-0000-00000000000b', P = '00000000-0000-0000-0000-00000000000c';
const SA = '10000000-0000-0000-0000-00000000000a', SM = '10000000-0000-0000-0000-00000000000b', SP = '10000000-0000-0000-0000-00000000000c';
await q(`insert into auth.users (id, email, email_confirmed_at, raw_user_meta_data) values ($1,'admin@vemax.com',now(),'{"nome":"Admin"}'), ($2,'membro@vemax.com',now(),'{"nome":"Membro"}')`, [A, M]);
await q(`update public.profiles set ativo = true, status = 'aprovado' where id = $1`, [M]);
await q(`insert into auth.users (id, email, email_confirmed_at, raw_user_meta_data) values ($1,'pendente@vemax.com',now(),'{"nome":"Pendente"}')`, [P]);
await q(`insert into auth.sessions (id, user_id) values ($1,$2), ($3,$4), ($5,$6)`, [SA, A, SM, M, SP, P]);
await q(`update public.permissoes set pode_ver = true, pode_editar = true where modulo = 'clientes'`);
const a = { uid: A, sid: SA }, m = { uid: M, sid: SM }, p = { uid: P, sid: SP };

console.log('\n## Sessão: revogação e duração máxima');
let r = await tenta(m, `insert into public.clientes (nome) values ('Cliente Teste') returning id`);
ok(!r.erro, 'sessão ativa: membro com permissão grava');
const cli = r.r.rows[0].id;
r = await tenta(m, `select count(*)::int n from public.clientes`);
ok(r.r.rows[0].n === 1, 'sessão ativa: lê clientes');
await q(`delete from auth.sessions where id = $1`, [SM]);                    // logout / sessão revogada
r = await tenta(m, `select count(*)::int n from public.clientes`);
ok(r.r.rows[0].n === 0, 'após logout/revogação, o MESMO token não lê mais nada (JWT não fica válido até expirar)');
r = await tenta(m, `insert into public.clientes (nome) values ('Depois do logout')`);
ok(r.erro, 'após logout, o mesmo token não consegue gravar');
await q(`insert into auth.sessions (id, user_id, created_at) values ($1,$2, now() - interval '13 hours')`, [SM, M]);
r = await tenta(m, `select count(*)::int n from public.clientes`);
ok(r.r.rows[0].n === 0, 'sessão com mais de 12 h (limite máximo) perde o acesso mesmo com token ainda válido');
r = await tenta(m, `select public.sessao_valida() as v`);
ok(r.r.rows[0].v === false, 'sessao_valida() devolve false para a tela poder deslogar');
await q(`update public.config_seguranca set valor = 0 where chave = 'sessao_max_horas'`);
r = await tenta(m, `select count(*)::int n from public.clientes`);
ok(r.r.rows[0].n === 1, 'limite desligado (0): volta a valer só a existência da sessão');
await q(`update public.config_seguranca set valor = 12 where chave = 'sessao_max_horas'`);
await q(`update auth.sessions set created_at = now() where id = $1`, [SM]);
r = await tenta(m, `select public.sessao_valida() as v`);
ok(r.r.rows[0].v === true, 'sessão recente é válida');
r = await tenta(null, `select public.sessao_valida() as v`);
ok(r.erro, 'visitante não executa sessao_valida()');

console.log('\n## 2FA (aal2) para administradores');
r = await tenta(a, `select public.is_admin() as v`);
ok(r.r.rows[0].v === true, 'admin sem 2FA cadastrado e exigência desligada: continua admin');
await q(`insert into auth.mfa_factors (user_id, status) values ($1, 'verified')`, [A]);
r = await tenta(a, `select public.is_admin() as v`);
ok(r.r.rows[0].v === false, 'admin COM 2FA mas sessão só de senha (aal1): NÃO age como admin');
r = await tenta(a, `select count(*)::int n from public.eventos_seguranca`);
ok(r.r.rows[0].n === 0 || r.r.rows.length === 1, 'sessão aal1 não lê o log de segurança (política exige admin)');
r = await tenta(a, `update public.permissoes set pode_ver = true where modulo = 'financeiro'`);
ok(!r.erro && r.r.affectedRows === 0, 'sessão aal1 do admin não altera permissões (0 linhas afetadas)');
r = await tenta({ ...a, aal: 'aal2' }, `select public.is_admin() as v`);
ok(r.r.rows[0].v === true, 'sessão aal2 (senha + código): admin pleno');
r = await tenta({ ...a, aal: 'aal2' }, `update public.permissoes set pode_ver = true where modulo = 'financeiro'`);
ok(!r.erro && r.r.affectedRows === 1, 'aal2 altera permissões');
await q(`update public.permissoes set pode_ver = false where modulo = 'financeiro'`);
await q(`delete from auth.mfa_factors where user_id = $1`, [A]);
await q(`update public.config_seguranca set valor = 1 where chave = 'exigir_mfa_admin'`);
r = await tenta(a, `select public.is_admin() as v`);
ok(r.r.rows[0].v === false, 'exigência ligada: admin SEM 2FA vira membro até ativar');
r = await tenta(a, `select public.can('clientes','ver') as v`);
ok(r.r.rows[0].v === true, '…mas mantém as permissões de membro (consegue entrar para ativar o 2FA)');
await q(`update public.config_seguranca set valor = 0 where chave = 'exigir_mfa_admin'`);
r = await tenta(m, `update public.config_seguranca set valor = 0 where chave = 'sessao_max_horas'`);
ok(r.erro || r.r.affectedRows === 0, 'membro não altera as configurações de segurança');

console.log('\n## Usuário pendente e matriz de permissões');
r = await tenta(p, `select count(*)::int n from public.permissoes`);
ok(r.r.rows[0].n === 0, 'cadastro pendente não lê a matriz de permissões');
r = await tenta(p, `select count(*)::int n from public.clientes`);
ok(r.r.rows[0].n === 0, 'cadastro pendente não lê clientes');
r = await tenta(p, `select count(*)::int n from public.profiles`);
ok(r.r.rows[0].n === 1, 'cadastro pendente só enxerga o próprio perfil');

console.log('\n## Eventos de segurança');
r = await tenta(m, `insert into public.eventos_seguranca (tipo, detalhe) values ('login_ok','forjado')`);
ok(r.erro, 'ninguém grava direto no log de segurança pelo navegador');
r = await tenta(a, `delete from public.eventos_seguranca`);
ok(r.erro || r.r.affectedRows === 0, 'ninguém apaga o histórico de segurança pelo navegador');
r = await tenta(m, `select public.registrar_evento('login_ok', E'linha1\\nlinha2') as x`);
ok(!r.erro, 'pessoa logada registra o próprio evento');
let ev = (await q(`select * from public.eventos_seguranca where tipo = 'login_ok'`)).rows[0];
ok(ev && ev.usuario_id === M && !ev.detalhe.includes('\n'), 'evento guarda o autor (do servidor) e remove quebras de linha');
r = await tenta(m, `select public.registrar_evento('apagar_tudo', 'x') as x`);
ok(r.erro, 'tipo de evento fora da lista é rejeitado');
r = await tenta(null, `select public.registrar_evento('login_ok', 'x') as x`);
ok(r.erro, 'visitante não registra evento de pessoa logada');
for (let i = 0; i < 70; i++) await tenta(m, `select public.registrar_evento('acesso_negado', 'teste') as x`);
ok((await q(`select count(*)::int n from public.eventos_seguranca where usuario_id = $1`, [M])).rows[0].n <= 60, 'limite de 60 eventos por hora por pessoa');

console.log('\n## Falhas de login: registro, alerta e privacidade');
const ipA = { ip: '203.0.113.7' };
for (let i = 0; i < 4; i++) await tenta(ipA, `select public.registrar_login_falho('Alvo@Vemax.com')`);
ok((await q(`select count(*)::int n from public.eventos_seguranca where tipo = 'alerta_forca_bruta'`)).rows[0].n === 0, '4 falhas ainda não geram alerta');
await tenta(ipA, `select public.registrar_login_falho('alvo@vemax.com')`);
ok((await q(`select count(*)::int n from public.eventos_seguranca where tipo = 'alerta_forca_bruta'`)).rows[0].n === 1, '5 falhas em 15 min geram alerta (e-mail normalizado: maiúsculas não escapam)');
for (let i = 0; i < 3; i++) await tenta(ipA, `select public.registrar_login_falho('alvo@vemax.com')`);
ok((await q(`select count(*)::int n from public.eventos_seguranca where tipo = 'alerta_forca_bruta'`)).rows[0].n === 1, 'não repete o alerta a cada tentativa (1 por hora)');
ok((await q(`select count(*)::int n from public.notificacoes where modulo = 'equipe' and titulo like 'Muitas falhas de login%'`)).rows[0].n === 1, 'administradores recebem notificação no sino');
const brutos = (await q(`select count(*)::int n from public.eventos_seguranca where detalhe ilike '%alvo@%' or email_hash ilike '%alvo@%' or ip_hash like '%203.0.113%'`)).rows[0].n;
ok(brutos === 0, 'o log não guarda e-mail nem IP em texto, só hash');
const hash = (await q(`select email_hash from public.eventos_seguranca where tipo = 'login_falha' limit 1`)).rows[0].email_hash;
ok(/^[a-f0-9]{64}$/.test(hash), 'hash do e-mail é sha256 (64 hex)');
r = await tenta({ ...a, aal: 'aal2' }, `select * from public.conta_do_hash($1)`, [hash]);
ok(r.r.rows.length === 0, 'hash de e-mail que NÃO é da equipe não revela nada');
await q(`update public.profiles set email = 'alvo@vemax.com' where id = $1`, [M]);
r = await tenta({ ...a, aal: 'aal2' }, `select * from public.conta_do_hash($1)`, [hash]);
ok(r.r.rows.length === 1 && r.r.rows[0].nome === 'Membro', 'admin descobre qual conta da equipe está sendo atacada');
r = await tenta(m, `select * from public.conta_do_hash($1)`, [hash]);
ok(r.r.rows.length === 0, 'membro não usa o localizador de contas');
for (let i = 0; i < 40; i++) await tenta({ ip: '198.51.100.9' }, `select public.registrar_login_falho('spam${i}@x.com')`);
ok((await q(`select count(*)::int n from public.eventos_seguranca where tipo = 'login_falha' and email_hash is not null`)).rows[0].n < 40 + 8, 'um único IP não consegue encher o log (limite de 30 por 10 min)');
r = await tenta(ipA, `select public.registrar_login_falho($1)`, ["'; drop table public.clientes; --"]);
ok(!r.erro && (await q(`select count(*)::int n from public.clientes`)).rows[0].n === 1, 'texto de ataque no e-mail é tratado como dado, nada é executado');

console.log('\n## Mudanças de permissão e papel entram no log de segurança');
await as({ ...a, aal: 'aal2' }, `update public.permissoes set pode_editar = true where modulo = 'suporte'`);
await as({ ...a, aal: 'aal2' }, `update public.profiles set papel = 'admin' where id = $1`, [M]);
await as({ ...a, aal: 'aal2' }, `update public.profiles set papel = 'membro' where id = $1`, [M]);
const tipos = (await q(`select tipo from public.eventos_seguranca where tipo in ('permissao_alterada','papel_alterado')`)).rows.map((x) => x.tipo);
ok(tipos.includes('permissao_alterada') && tipos.filter((t) => t === 'papel_alterado').length === 2, 'permissão e papel alterados ficam registrados');
ok((await q(`select count(*)::int n from public.eventos_seguranca where tipo = 'cadastro_solicitado'`)).rows[0].n >= 1, 'cadastro pendente fica registrado');

console.log('\n## Formulário público: limite por IP e formato do contato');
const lead = (ip, contato, nome = 'Visitante') => tenta({ ip }, `insert into public.contatos_site (nome, contato, mensagem) values ($1,$2,'Quero um site')`, [nome, contato]);
r = await lead('192.0.2.1', 'ana@exemplo.com'); ok(!r.erro, 'e-mail válido é aceito');
r = await lead('192.0.2.1', '(11) 99999-8888', 'Zé'); ok(!r.erro, 'telefone com máscara é aceito');
r = await lead('192.0.2.1', 'Maria whatsapp 11 9999'); ok(r.erro && /e-mail ou telefone/.test(r.erro), 'texto livre sem e-mail/telefone é rejeitado no servidor');
r = await lead('192.0.2.1', 'x@y'); ok(r.erro, 'e-mail sem domínio completo é rejeitado');
r = await lead('192.0.2.1', '12345'); ok(r.erro, 'telefone curto demais é rejeitado');
for (let i = 0; i < 6; i++) r = await lead('192.0.2.50', `pessoa${i}@exemplo.com`);
ok(r.erro && /deste acesso/.test(r.erro), 'mais de 5 mensagens por hora do mesmo IP são barradas');
r = await lead('192.0.2.77', 'outra@exemplo.com'); ok(!r.erro, 'outro IP não é afetado (sem bloqueio global por um único cliente)');
ok((await q(`select count(*)::int n from public.contatos_site where ip_hash like '%192.0.2%'`)).rows[0].n === 0, 'o IP não é guardado em texto no lead');
r = await tenta({ ip: '192.0.2.99' }, `insert into public.contatos_site (nome, contato, mensagem, ip_hash) values ('Fraude','f@x.com','ola','forjado')`);
ok(!r.erro && (await q(`select ip_hash from public.contatos_site where nome = 'Fraude'`)).rows[0].ip_hash !== 'forjado', 'o cliente não consegue forjar o campo ip_hash');

console.log('\n## Validações de formato no banco');
r = await tenta(a, `select public.documento_valido('52998224725') a, public.documento_valido('11222333000181') b, public.documento_valido('12345678901') c, public.documento_valido('11111111111') d, public.documento_valido('') e, public.documento_valido('1234') f, public.documento_valido('11222333000182') g`);
